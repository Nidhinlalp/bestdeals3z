function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function buildDescription(s: Seed): string {
  const cat = categoryName(s.cat);
  return `${s.short} Part of our ${cat} edit, the ${s.name} pairs a premium build with everyday usability. ${s.highlights[0]} and ${s.highlights[1]?.toLowerCase() ?? 'thoughtful design'} make it a standout pick, while a clean, modern finish means it looks as good as it performs. Backed by easy WhatsApp ordering, fast delivery and a hassle-free return window.`;
}

export const products: Product[] = seeds.map((s, i) => {
  const slug = slugify(s.name);
  const badges: ProductBadge[] = [...(s.badges ?? [])];
  if (s.flags?.flashSale && !badges.includes('flash')) badges.push('flash');
  return {
    id: `p${i + 1}`,
    slug,
    name: s.name,
    brand: s.brand,
    category: s.cat,
    categoryName: categoryName(s.cat),
    price: s.price,
    mrp: s.mrp,
    rating: s.rating,
    reviews: s.reviews,
    images: [
      img(`${slug}-1`, 900, 900),
      img(`${slug}-2`, 900, 900),
      img(`${slug}-3`, 900, 900),
      img(`${slug}-4`, 900, 900),
    ],
    badges,
    inStock: (s.stock ?? 50) > 0,
    stockCount: s.stock ?? 50,
    shortDescription: s.short,
    description: buildDescription(s),
    highlights: s.highlights,
    specs: s.specs,
    variants: s.variants ?? [],
    tags: s.tags ?? [s.brand.toLowerCase(), s.cat],
    featured: !!s.flags?.featured,
    trending: !!s.flags?.trending,
    bestseller: !!s.flags?.bestseller,
    flashSale: !!s.flags?.flashSale,
    deliveryDays: s.delivery ?? 3,
  };
});

